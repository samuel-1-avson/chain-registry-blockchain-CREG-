# Create or refresh testnet/sepolia-fleet.env for maintainer seed fleet on GCP.
#
# Usage:
#   .\testnet\init-sepolia-fleet-env.ps1
#   .\testnet\init-sepolia-fleet-env.ps1 -RpcUrl "https://sepolia.infura.io/v3/YOUR_KEY"
#   .\testnet\init-sepolia-fleet-env.ps1 -Force

param(
    [string]$RpcUrl = "https://ethereum-sepolia-rpc.publicnode.com",
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot = Split-Path -Parent $scriptDir
$outPath = Join-Path $scriptDir "sepolia-fleet.env"

if ((Test-Path $outPath) -and -not $Force) {
    Write-Host "Already exists: $outPath" -ForegroundColor Yellow
    Write-Host "Re-run with -Force to overwrite, or edit the file manually."
    exit 0
}

$key1 = "9d91e9e0d82a02b7be8c40a522d899eea9eeffad244323be3e568973211f3a6d"

$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
$bytes = New-Object byte[] 32
$rng.GetBytes($bytes)
$key2 = ([BitConverter]::ToString($bytes) -replace '-', '').ToLower()

Set-Location $repoRoot
$pub1 = (cargo run -q --example ed25519_pubkey_from_secret -p common -- $key1 2>&1 | Select-Object -Last 1).Trim()
$pub2 = (cargo run -q --example ed25519_pubkey_from_secret -p common -- $key2 2>&1 | Select-Object -Last 1).Trim()

$content = @"
# Generated by init-sepolia-fleet-env.ps1 — gitignored; safe to edit.
# Architecture: docs/TESTNET_SCALE_ARCHITECTURE.md
SEPOLIA_RPC_URL=$RpcUrl
CREG_ETH_RPC=$RpcUrl
CREG_FLEET_IPFS_HOST_PORT=15001
CREG_FLEET_SPEC_HOST_PORT=18888
CREG_FLEET_NODE1_API_PORT=28180
CREG_FLEET_NODE1_P2P_PORT=29100
CREG_FLEET_NODE2_API_PORT=28181
CREG_FLEET_NODE2_P2P_PORT=29101
CREG_FLEET_OBSERVER_API_PORT=28182
CREG_FLEET_OBSERVER_P2P_PORT=29102
CREG_3NODE_IPFS_HOST_PORT=15001
CREG_3NODE_SPEC_HOST_PORT=18888
CREG_3NODE_NODE1_API_PORT=28180
CREG_3NODE_NODE1_P2P_PORT=29100
CREG_3NODE_NODE2_API_PORT=28181
CREG_3NODE_NODE2_P2P_PORT=29101
CREG_3NODE_NODE3_API_PORT=28182
CREG_3NODE_NODE3_P2P_PORT=29102
CREG_DEV_SANDBOX=false
CREG_VALIDATOR_KEY_1=$key1
CREG_VALIDATOR_KEY_2=$key2
# core-1 pubkey: $pub1
# validator-2 pubkey: $pub2
"@

Set-Content -Path $outPath -Value $content -Encoding UTF8
Write-Host "Wrote $outPath" -ForegroundColor Green
Write-Host "Next: set CREG_EDGE_INTERNAL_IP, then ./testnet/start-validator-fleet-gcp.sh on the validator VM"