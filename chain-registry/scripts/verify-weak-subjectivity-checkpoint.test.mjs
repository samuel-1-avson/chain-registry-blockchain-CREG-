test("publish and verify-evidence CLI writes a reusable signed record", () => {
  const fixture = initialFixture();
  const directory = mkdtempSync(join(tmpdir(), "creg-checkpoint-gate-"));
  try {
    const checkpointPath = join(directory, "checkpoint.json");
    const previousSetPath = join(directory, "previous-set.json");
    const anchorPath = join(directory, "anchor.json");
    const privateKeyPath = join(directory, "verifier.pem");
    const evidencePath = join(directory, "evidence.json");
    writeFileSync(checkpointPath, JSON.stringify(fixture.checkpoint));
    writeFileSync(previousSetPath, JSON.stringify(fixture.previous.set));
    writeFileSync(anchorPath, JSON.stringify(fixture.input.canonicalAnchor));
    writeFileSync(privateKeyPath, fixture.verifier.privatePem, {
      mode: 0o600,
    });

    const publish = spawnSync(
      process.execPath,
      [
        scriptPath,
        "publish",
        "--checkpoint",
        checkpointPath,
        "--previous-validator-set",
        previousSetPath,
        "--canonical-anchor",
        anchorPath,
        "--max-anchor-age-blocks",
        "10",
        "--verifier-id",
        "cli-test-verifier",
        "--verified-at",
        "2026-07-29T10:01:00Z",
        "--evidence-signing-key",
        privateKeyPath,
        "--initial-release",
        "--output",
        evidencePath,
      ],
      { encoding: "utf8" },
    );
    assert.equal(publish.status, 0, publish.stderr);
    assert.equal(JSON.parse(publish.stdout).status, "verified-and-signed");
    const envelope = JSON.parse(readFileSync(evidencePath, "utf8"));
    assert.equal(
      envelope.payload.logical_transition_id,
      logicalTransitionId(fixture.checkpoint),
    );

    const verify = spawnSync(
      process.execPath,
      [
        scriptPath,
        "verify-evidence",
        "--evidence",
        evidencePath,
        "--trusted-verifier-public-key",
        fixture.verifier.publicKeyHex,
      ],
      { encoding: "utf8" },
    );
    assert.equal(verify.status, 0, verify.stderr);
    assert.equal(JSON.parse(verify.stdout).status, "valid");
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
});
