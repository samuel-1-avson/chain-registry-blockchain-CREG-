import React from 'react'
import { useFetch } from '../hooks/useFetch.js'
import { nodeApi } from '../api/node.js'
import { SkeletonCard } from './Skeleton.jsx'
import { ErrorState } from './ErrorState.jsx'
import { StatusBadge } from './StatusBadge.jsx'

// ADR-019 §11 #7: the node serves only the quantized IntelligenceSummaryV1
// (status, 0-100 score, closed risk tier, degraded flag). No LLM-authored
// text reaches the explorer, so every label below is static.

const STATUS_LABELS = {
  pending: 'pending',
  ready: 'ready',
  degraded: 'degraded',
  failed: 'failed',
}

const RISK_TIER_LABELS = {
  clean: 'Clean',
  suspicious: 'Suspicious',
  likely_malicious: 'Likely malicious',
  confirmed_malicious: 'Confirmed malicious',
  unknown: 'Unknown',
}

function statusVariant(status) {
  switch (status) {
    case 'ready':
      return 'success'
    case 'degraded':
      return 'warning'
    case 'failed':
      return 'error'
    case 'pending':
    default:
      return 'neutral'
  }
}

function Row({ label, children }) {
  return (
    <div style={{ display: 'flex', gap: 'var(--space-3)', fontSize: 13 }}>
      <span style={{ minWidth: 140, color: 'var(--text-tertiary)' }}>{label}</span>
      <span style={{ color: 'var(--text-secondary)' }}>{children}</span>
    </div>
  )
}

export function PackageIntelligencePanel({ canonical }) {
  const { data, error, loading, refetch } = useFetch(
    (s) => nodeApi.packageIntelligence(canonical, s),
    { deps: [canonical] },
  )

  if (loading && !data) return <SkeletonCard lines={4} />
  if (error) return <ErrorState error={error} onRetry={refetch} title="Deep analysis unavailable" />

  const status = STATUS_LABELS[data?.status] || 'pending'
  const score = Number.isInteger(data?.maliciousness_score)
    ? Math.min(Math.max(data.maliciousness_score, 0), 100)
    : null
  const tier = RISK_TIER_LABELS[data?.risk_tier] || null
  const generatedAt = Number.isInteger(data?.generated_at_unix)
    ? new Date(data.generated_at_unix * 1000).toISOString()
    : null

  return (
    <div className="ce-card" style={{ display: 'grid', gap: 'var(--space-4)' }}>
      <header style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-3)', flexWrap: 'wrap' }}>
        <h2 style={{ margin: 0, fontSize: 16 }}>Deep Analysis</h2>
        <StatusBadge variant={statusVariant(status)}>{status}</StatusBadge>
        <span style={{ fontSize: 11, color: 'var(--text-tertiary)' }}>
          Lane C, advisory only: never used for consensus or install decisions
        </span>
      </header>

      {status === 'pending' ? (
        <p style={{ margin: 0, fontSize: 13, color: 'var(--text-secondary)' }}>
          No report yet. Reports are generated by the validator's agent runner when intelligence is enabled.
        </p>
      ) : (
        <div style={{ display: 'grid', gap: 'var(--space-2)' }}>
          <Row label="Risk tier">{tier ?? 'Not reported'}</Row>
          <Row label="Score (0-100)">{score ?? 'Not reported'}</Row>
          <Row label="Degraded">{data?.degraded ? 'Yes: produced without a full model run' : 'No'}</Row>
          {generatedAt && <Row label="Generated">{generatedAt}</Row>}
          {data?.report_digest && (
            <Row label="Report digest">
              <code style={{ fontSize: 12 }}>{String(data.report_digest).slice(0, 64)}</code>
            </Row>
          )}
        </div>
      )}
    </div>
  )
}
