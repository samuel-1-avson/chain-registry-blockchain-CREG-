// crates/cli/src/sbom.rs
// `creg sbom` — SBOM export.
//
// Workspace mode (`--workspace`) inventories every crate in Cargo.lock.
// Package mode still talks to the node; if the chain record has no dependency
// list, the document is marked incomplete instead of pretending one component
// is a full BOM (HI-19).

use anyhow::{Context, Result};
use chrono::Utc;
use colored::Colorize;

#[derive(Debug, Clone, Copy)]
pub enum SbomFormat {
    Spdx,
    CycloneDx,
}

impl std::str::FromStr for SbomFormat {
    type Err = anyhow::Error;
    fn from_str(s: &str) -> Result<Self> {
        match s.to_lowercase().as_str() {
            "spdx" => Ok(SbomFormat::Spdx),
            "cyclonedx" | "cdx" => Ok(SbomFormat::CycloneDx),
            _ => anyhow::bail!("Unknown SBOM format: '{}'. Use 'spdx' or 'cyclonedx'.", s),
        }
    }
}

pub async fn run(
    package: Option<&str>,
    ecosystem: Option<&str>,
    format: SbomFormat,
    output: Option<&std::path::Path>,
    node_url: Option<&str>,
    workspace: bool,
    lockfile: Option<&std::path::Path>,
) -> Result<()> {
    if workspace {
        if package.is_some() {
            anyhow::bail!("pass either a package name or --workspace, not both");
        }
        return crate::supply_chain::run_workspace_sbom(format, output, lockfile);
    }
    let package = package
        .ok_or_else(|| anyhow::anyhow!("package name is required unless --workspace is set"))?;
    let base = node_url.map(String::from).unwrap_or_else(|| {
        std::env::var("CREG_NODE_URL").unwrap_or_else(|_| "http://localhost:8080".into())
    });

    let canonical = if package.contains(':') {
        package.to_string()
    } else {
        let eco = ecosystem.unwrap_or("npm");
        let (name, ver) = if let Some(idx) = package.rfind('@') {
            (&package[..idx], &package[idx + 1..])
        } else {
            (package, "latest")
        };
        format!("{}:{}@{}", eco, name, ver)
    };

    println!(
        "{} Generating SBOM for {} ...",
        "→".cyan(),
        canonical.bold()
    );

    let encoded = urlencoding::encode(&canonical);
    let url = format!("{}/v1/packages/{}", base.trim_end_matches('/'), encoded);

    let resp = reqwest::Client::new()
        .get(&url)
        .timeout(std::time::Duration::from_secs(10))
        .send()
        .await
        .context("Failed to reach registry node")?;

    if !resp.status().is_success() {
        anyhow::bail!("Package '{}' not found (HTTP {})", canonical, resp.status());
    }

    let record: serde_json::Value = resp
        .json()
        .await
        .context("Failed to parse package record")?;

    let sbom_doc = match format {
        SbomFormat::Spdx => generate_spdx(&canonical, &record)?,
        SbomFormat::CycloneDx => generate_cyclonedx(&canonical, &record)?,
    };

    let pretty = serde_json::to_string_pretty(&sbom_doc)?;

    if let Some(path) = output {
        std::fs::write(path, &pretty)
            .with_context(|| format!("Failed to write SBOM to {}", path.display()))?;
        println!("{} SBOM saved to {}", "✓".green(), path.display());
    } else {
        println!("{}", pretty);
    }

    Ok(())
}

fn generate_spdx(canonical: &str, record: &serde_json::Value) -> Result<serde_json::Value> {
    let content_hash = record
        .get("content_hash")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let publisher = record
        .get("publisher")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown");
    let status = record
        .get("status")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown");
    let published_at = record
        .get("published_at")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let ipfs_cid = record
        .get("ipfs_cid")
        .and_then(|v| v.as_str())
        .unwrap_or("");

    // Parse canonical → name + version
    let (name, version) = parse_canonical(canonical);
    let deps = declared_dependencies(record);
    let completeness = if deps.is_empty() {
        "incomplete"
    } else {
        "declared-dependencies"
    };

    let doc_namespace = format!(
        "https://chain-registry.io/sbom/{}/{}",
        canonical,
        Utc::now().timestamp()
    );

    Ok(serde_json::json!({
        "spdxVersion": "SPDX-2.3",
        "dataLicense": "CC0-1.0",
        "SPDXID": "SPDXRef-DOCUMENT",
        "name": format!("{}-sbom", name),
        "documentNamespace": doc_namespace,
        "creationInfo": {
            "created": Utc::now().to_rfc3339(),
            "creators": [
                format!("Tool: creg/chain-registry"),
                format!("Organization: Chain Registry"),
            ],
            "comment": format!("Generated by creg sbom; creg:completeness={completeness}")
        },
        "comment": format!("creg:completeness={completeness}"),
        "packages": spdx_packages(&name, &version, canonical, content_hash, publisher, status, ipfs_cid, published_at, &deps),
        "relationships": spdx_relationships(deps.len())
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn record_without_deps() -> serde_json::Value {
        serde_json::json!({
            "content_hash": "ab".repeat(32),
            "publisher": "alice",
            "status": "verified",
            "published_at": "2026-08-23T00:00:00Z",
            "ipfs_cid": "bafytest"
        })
    }

    #[test]
    fn package_sbom_without_deps_is_marked_incomplete() {
        let doc = generate_spdx("npm:left-pad@1.0.0", &record_without_deps()).unwrap();
        assert_eq!(doc["comment"], "creg:completeness=incomplete");
        assert_eq!(doc["packages"].as_array().unwrap().len(), 1);
        let cdx = generate_cyclonedx("npm:left-pad@1.0.0", &record_without_deps()).unwrap();
        assert_eq!(cdx["specVersion"], "1.5");
        assert_eq!(cdx["metadata"]["properties"][0]["value"], "incomplete");
    }

    #[test]
    fn package_sbom_includes_declared_dependencies() {
        let mut record = record_without_deps();
        record["dependencies"] = serde_json::json!({
            "escape-html": "1.0.3",
            "ms": { "version": "2.1.3" }
        });
        let doc = generate_spdx("npm:express@4.18.2", &record).unwrap();
        assert_eq!(doc["comment"], "creg:completeness=declared-dependencies");
        assert_eq!(doc["packages"].as_array().unwrap().len(), 3);
        let rels = doc["relationships"].as_array().unwrap();
        assert!(rels
            .iter()
            .any(|rel| rel["relationshipType"] == "DEPENDS_ON"));
    }
}

fn generate_cyclonedx(canonical: &str, record: &serde_json::Value) -> Result<serde_json::Value> {
    let content_hash = record
        .get("content_hash")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let publisher = record
        .get("publisher")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown");
    let status = record
        .get("status")
        .and_then(|v| v.as_str())
        .unwrap_or("unknown");
    let published_at = record
        .get("published_at")
        .and_then(|v| v.as_str())
        .unwrap_or("");
    let ipfs_cid = record
        .get("ipfs_cid")
        .and_then(|v| v.as_str())
        .unwrap_or("");

    let (name, version) = parse_canonical(canonical);
    let deps = declared_dependencies(record);
    let completeness = if deps.is_empty() {
        "incomplete"
    } else {
        "declared-dependencies"
    };
    let bom_ref = format!("pkg:chain-registry/{}/{}", name, version);

    Ok(serde_json::json!({
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": format!("urn:uuid:{}", uuid_from_canonical(canonical)),
        "version": 1,
        "metadata": {
            "timestamp": Utc::now().to_rfc3339(),
            "tools": {
                "components": [{
                    "type": "application",
                    "name": "creg",
                    "version": env!("CARGO_PKG_VERSION")
                }]
            },
            "component": {
                "type": "library",
                "bom-ref": bom_ref,
                "name": name,
                "version": version
            },
            "properties": [
                { "name": "creg:completeness", "value": completeness },
                { "name": "creg:canonical", "value": canonical }
            ]
        },
        "components": cyclone_components(
            &name,
            &version,
            canonical,
            content_hash,
            publisher,
            status,
            published_at,
            ipfs_cid,
            &deps,
        )
    }))
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct DeclaredDep {
    name: String,
    version: String,
}

fn declared_dependencies(record: &serde_json::Value) -> Vec<DeclaredDep> {
    let mut out = Vec::new();
    collect_deps(record.get("dependencies"), &mut out);
    collect_deps(record.pointer("/manifest/dependencies"), &mut out);
    out.sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));
    out.dedup();
    out
}

fn collect_deps(value: Option<&serde_json::Value>, out: &mut Vec<DeclaredDep>) {
    let Some(value) = value else {
        return;
    };
    if let Some(array) = value.as_array() {
        for entry in array {
            if let Some(s) = entry.as_str() {
                out.push(parse_dep_spec(s));
            } else if let Some(obj) = entry.as_object() {
                let name = obj
                    .get("name")
                    .and_then(|v| v.as_str())
                    .unwrap_or("")
                    .to_string();
                let version = obj
                    .get("version")
                    .and_then(|v| v.as_str())
                    .unwrap_or("unknown")
                    .to_string();
                if !name.is_empty() {
                    out.push(DeclaredDep { name, version });
                }
            }
        }
        return;
    }
    if let Some(map) = value.as_object() {
        for (name, spec) in map {
            let version = spec
                .as_str()
                .or_else(|| spec.get("version").and_then(|v| v.as_str()))
                .unwrap_or("unknown");
            out.push(DeclaredDep {
                name: name.clone(),
                version: version.to_string(),
            });
        }
    }
}

fn parse_dep_spec(spec: &str) -> DeclaredDep {
    if let Some((name, version)) = spec.rsplit_once('@') {
        DeclaredDep {
            name: name.to_string(),
            version: version.to_string(),
        }
    } else {
        DeclaredDep {
            name: spec.to_string(),
            version: "unknown".into(),
        }
    }
}

fn spdx_packages(
    name: &str,
    version: &str,
    canonical: &str,
    content_hash: &str,
    publisher: &str,
    status: &str,
    ipfs_cid: &str,
    published_at: &str,
    deps: &[DeclaredDep],
) -> Vec<serde_json::Value> {
    let mut packages = vec![serde_json::json!({
        "SPDXID": "SPDXRef-Package",
        "name": name,
        "versionInfo": version,
        "downloadLocation": format!("ipfs://{}", ipfs_cid),
        "filesAnalyzed": false,
        "checksums": [{
            "algorithm": "SHA256",
            "checksumValue": content_hash,
        }],
        "supplier": format!("Organization: {}", &publisher[..publisher.len().min(16)]),
        "originator": format!("Organization: {}", &publisher[..publisher.len().min(16)]),
        "primaryPackagePurpose": "LIBRARY",
        "externalRefs": [
            {
                "referenceCategory": "PACKAGE-MANAGER",
                "referenceType": "purl",
                "referenceLocator": canonical,
            },
            {
                "referenceCategory": "OTHER",
                "referenceType": "verification-status",
                "referenceLocator": format!("status:{}", status),
            }
        ],
        "annotations": [
            {
                "annotator": "Tool: creg",
                "annotationDate": Utc::now().to_rfc3339(),
                "annotationType": "OTHER",
                "comment": format!("Published at: {}; Chain status: {}", published_at, status),
            }
        ]
    })];
    for (index, dep) in deps.iter().enumerate() {
        packages.push(serde_json::json!({
            "SPDXID": format!("SPDXRef-Dep-{index}"),
            "name": dep.name,
            "versionInfo": dep.version,
            "downloadLocation": "NOASSERTION",
            "filesAnalyzed": false
        }));
    }
    packages
}

fn spdx_relationships(dep_count: usize) -> Vec<serde_json::Value> {
    let mut rels = vec![serde_json::json!({
        "spdxElementId": "SPDXRef-DOCUMENT",
        "relationshipType": "DESCRIBES",
        "relatedSpdxElement": "SPDXRef-Package"
    })];
    for index in 0..dep_count {
        rels.push(serde_json::json!({
            "spdxElementId": "SPDXRef-Package",
            "relationshipType": "DEPENDS_ON",
            "relatedSpdxElement": format!("SPDXRef-Dep-{index}")
        }));
    }
    rels
}

fn cyclone_components(
    name: &str,
    version: &str,
    canonical: &str,
    content_hash: &str,
    publisher: &str,
    status: &str,
    published_at: &str,
    ipfs_cid: &str,
    deps: &[DeclaredDep],
) -> Vec<serde_json::Value> {
    let mut components = vec![serde_json::json!({
        "type": "library",
        "bom-ref": format!("pkg:chain-registry/{name}/{version}"),
        "name": name,
        "version": version,
        "purl": format!("pkg:{canonical}"),
        "hashes": [{ "alg": "SHA-256", "content": content_hash }],
        "externalReferences": [
            {
                "type": "distribution",
                "url": format!("ipfs://{ipfs_cid}"),
                "comment": "IPFS content address"
            }
        ],
        "properties": [
            { "name": "chain-registry:status", "value": status },
            { "name": "chain-registry:published_at", "value": published_at },
            { "name": "chain-registry:publisher", "value": &publisher[..publisher.len().min(20)] },
            { "name": "chain-registry:canonical", "value": canonical },
        ]
    })];
    for dep in deps {
        components.push(serde_json::json!({
            "type": "library",
            "name": dep.name,
            "version": dep.version,
            "bom-ref": format!("dep:{}@{}", dep.name, dep.version)
        }));
    }
    components
}

fn parse_canonical(canonical: &str) -> (String, String) {
    // canonical format: ecosystem:name@version
    let without_eco = canonical.split(':').nth(1).unwrap_or(canonical);
    if let Some(idx) = without_eco.rfind('@') {
        (
            without_eco[..idx].to_string(),
            without_eco[idx + 1..].to_string(),
        )
    } else {
        (without_eco.to_string(), "unknown".to_string())
    }
}

/// Deterministic pseudo-UUID from canonical string (no rand dependency needed).
fn uuid_from_canonical(canonical: &str) -> String {
    use std::hash::{Hash, Hasher};
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    canonical.hash(&mut hasher);
    let h = hasher.finish();
    format!("{:016x}-0000-4000-8000-000000000000", h)
}
